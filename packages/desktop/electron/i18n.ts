/**
 * Sprache des Hauptprozesses — unabhängig von der Sprache des
 * Renderer-Fensters (die kennt der Hauptprozess von sich aus nicht).
 *
 * Startwert: die Systemsprache (app.getLocale()), auf die nächstgelegene
 * unterstützte Sprache abgebildet — das Einzige, was beim allerersten
 * Menüaufbau überhaupt bekannt ist (siehe main.ts, app.whenReady). Sobald
 * die Ansicht geladen hat und weiß, welche Sprache tatsächlich eingestellt
 * ist (state/store.ts, applyTheme — kann von der Systemsprache abweichen),
 * meldet sie das über IPC ('app:language', siehe preload.ts/main.ts) und
 * spracheSetzen() unten übernimmt sie. Das Menü baut main.ts danach neu auf.
 */
let aktuelleSprache = 'en';

/** Auf die nächstgelegene unterstützte Kurzform abbilden — 'de-DE' → 'de'.
 *  Unbekannte Sprache bleibt unangetastet (aktuelleSprache ändert sich nicht). */
export function spracheSetzen(sprache: string): void {
  const kurz = (sprache || '').toLowerCase().split(/[-_]/)[0];
  if (WOERTERBUECHER[kurz]) aktuelleSprache = kurz;
}

export function aktuelleMainSprache(): string {
  return aktuelleSprache;
}

/**
 * Übersetzt einen Schlüssel in die aktuell bekannte Sprache.
 *
 * Rückfallkette wie kern.ts: eigene Sprache → Deutsch → der Schlüssel selbst
 * (kann hier praktisch nicht eintreten, jede Sprache hat jeden Schlüssel —
 * geprüft von scripts/hauptprozess-woerterbuch-pruefen.mjs).
 * Platzhalter `{name}` wie in kern.ts, absichtlich derselbe reguläre
 * Ausdruck, damit ein Text ohne Änderung zwischen beiden Wörterbüchern
 * wandern kann.
 */
export function t(key: MainKey, werte?: Record<string, string | number>): string {
  const wb = WOERTERBUECHER[aktuelleSprache];
  const roh = wb?.[key] ?? WOERTERBUECHER.de[key] ?? key;
  if (!werte) return roh;
  return roh.replace(/\{\{?(\w+)\}?\}/g, (ganz, name) => String(werte[name] ?? ganz));
}

/** Zahl in der aktuellen Hauptprozess-Sprache formatieren — für Meldungen
 *  wie "{noetig} GB nötig" (siehe updater.ts). Ohne Intl.NumberFormat kommt
 *  bei .toFixed(1) immer ein Punkt heraus, auch für Sprachen, die ein Komma
 *  erwarten. */
export function zahlFormatieren(n: number, nachkommastellen = 1): string {
  try {
    return new Intl.NumberFormat(aktuelleSprache, {
      minimumFractionDigits: nachkommastellen,
      maximumFractionDigits: nachkommastellen,
    }).format(n);
  } catch {
    return n.toFixed(nachkommastellen);
  }
}

/**
 * Beste erste Vermutung beim Programmstart — VOR jedem app:language von der
 * Ansicht. Nur hier wird app.getLocale() für Sprache verwendet; nach dem
 * ersten app:language übernimmt ausschließlich das, was die Ansicht meldet.
 */
export function anfangsSpracheSetzen(): void {
  spracheSetzen(app.getLocale());
}
